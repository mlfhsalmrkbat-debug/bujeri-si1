export function getRestaurantByIdOrSlug(idOrSlug) {
  if (!idOrSlug) return null;
  const byId = RESTAURANTS_DETAILS[idOrSlug];
  const base =
    byId ||
    Object.values(RESTAURANTS_DETAILS).find(
      (r) => r.slug.toLowerCase() === String(idOrSlug).toLowerCase(),
    );
  if (!base) return null;

  // Dynamically compute fresh dates starting from today
  return {
    ...base,
    dates: getDynamicDates(30),
  };
}
