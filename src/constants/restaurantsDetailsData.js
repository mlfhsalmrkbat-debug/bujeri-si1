// Dynamic dates generator for reservation selectors
export function getDynamicDates(daysCount = 30) {
  const arDays = [
    "الأحد",
    "الاثنين",
    "الثلاثاء",
    "الأربعاء",
    "الخميس",
    "الجمعة",
    "السبت",
  ];
  const arMonths = [
    "يناير",
    "فبراير",
    "مارس",
    "أبريل",
    "مايو",
    "يونيو",
    "يوليو",
    "أغسطس",
    "سبتمبر",
    "أكتوبر",
    "نوفمبر",
    "ديسمبر",
  ];
  const enDays = [
    "Sunday",
    "Monday",
    "Tuesday",
    "Wednesday",
    "Thursday",
    "Friday",
    "Saturday",
  ];
  const enMonths = [
    "Jan",
    "Feb",
    "Mar",
    "Apr",
    "May",
    "Jun",
    "Jul",
    "Aug",
    "Sep",
    "Oct",
    "Nov",
    "Dec",
  ];

  const dates = [];
  const now = new Date();

  for (let i = 0; i < daysCount; i++) {
    const d = new Date(now);
    d.setDate(now.getDate() + i);

    const year = d.getFullYear();
    const month = String(d.getMonth() + 1).padStart(2, "0");
    const day = String(d.getDate()).padStart(2, "0");
    const value = `${year}-${month}-${day}`;

    const dayNameAr = arDays[d.getDay()];
    const monthNameAr = arMonths[d.getMonth()];
    const labelAr = `${dayNameAr}, ${day}-${monthNameAr}-${year}`;

    const dayNameEn = enDays[d.getDay()];
    const monthNameEn = enMonths[d.getMonth()];
    const labelEn = `${dayNameEn}, ${day}-${monthNameEn}-${year}`;

    dates.push({ value, labelAr, labelEn });
  }

  return dates;
}

